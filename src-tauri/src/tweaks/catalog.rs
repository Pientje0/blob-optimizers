macro_rules! deny_app_access {
    ($id:literal, $cap:literal, $title:literal, $desc:literal, $rec:expr) => {
        t(
            $id,
            PRIV,
            "App permissions",
            $title,
            $desc,
            Some("Apps that need this permission ask again or stop offering the feature. You can allow it again here at any time."),
            &[Set(CU, concat!(r"Software\Microsoft\Windows\CurrentVersion\CapabilityAccessManager\ConsentStore\", $cap), "Value", S("Deny"))],
            &[Opt(CU, concat!(r"Software\Microsoft\Windows\CurrentVersion\CapabilityAccessManager\ConsentStore\", $cap), "Value", S("Allow"))],
            $rec,
            Nothing,
            0,
        )
    };
}

