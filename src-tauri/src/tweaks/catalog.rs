#[allow(clippy::too_many_arguments)]
const fn t(
    id: &'static str,
    category: Category,
    group: &'static str,
    title: &'static str,
    description: &'static str,
    caveat: Option<&'static str>,
    on: &'static [Op],
    off: &'static [Op],
    recommend: Recommend,
    after: After,
    min_build: u32,
) -> Tweak {
    Tweak { id, title, description, caveat, category, group, on, off, recommend, after, min_build, default_on: false }
}

